//! Open tabs with their unsaved drafts (replacing the old localStorage), the
//! receipt settings and the idle-lock minutes.

use crate::crm::Crm;
use crate::error::{Result, ServiceError};
use crate::messages;
use crm_domain::{OrderDraft, OrderId, OrderKind, time};
use crm_storage::repo::{settings, tabs};

/// Idle-lock minutes allowed (0 = off).
pub const IDLE_LOCK_RANGE: std::ops::RangeInclusive<u32> = 0..=120;

/// Receipt width range in mm.
pub const RECEIPT_WIDTH_RANGE: std::ops::RangeInclusive<u32> = 48..=110;
/// Receipt font size range in points.
pub const RECEIPT_FONT_RANGE: std::ops::RangeInclusive<u32> = 6..=14;

/// One open order tab as the workspace persists it.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct OpenTab {
    /// Key generated by the UI.
    pub tab_key: String,
    /// Left-to-right position.
    pub position: i64,
    /// Shitje / Blerje.
    pub kind: OrderKind,
    /// The saved order shown, or `None` for a new one.
    pub order_id: Option<OrderId>,
    /// Tab title.
    pub title: String,
    /// Whether this is the selected tab (saving an active tab clears the others').
    pub active: bool,
    /// The unsaved draft (`None` = no unsaved changes), stored as JSON.
    pub draft: Option<OrderDraft>,
}

/// Receipt layout settings (used by 012).
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct ReceiptSettings {
    /// Paper width, 48..=110 mm (default 72).
    pub width_mm: u32,
    /// Font size, 6..=14 pt (default 9).
    pub font_pt: u32,
}

impl Default for ReceiptSettings {
    fn default() -> Self {
        ReceiptSettings {
            width_mm: settings::DEFAULT_RECEIPT_WIDTH_MM,
            font_pt: settings::DEFAULT_RECEIPT_FONT_PT,
        }
    }
}

/// `value` when it is inside `range`, else `default` (logged).
fn in_range_or_default(
    key: &str,
    value: u32,
    range: std::ops::RangeInclusive<u32>,
    default: u32,
) -> u32 {
    if range.contains(&value) {
        value
    } else {
        tracing::warn!("setting {key} = {value} is outside {range:?}; using {default}");
        default
    }
}

fn from_stored(tab: tabs::OpenTab) -> OpenTab {
    let draft = tab
        .draft_json
        .as_deref()
        .and_then(|json| match serde_json::from_str(json) {
            Ok(draft) => Some(draft),
            Err(e) => {
                // A draft from an incompatible version: drop it, keep the tab.
                tracing::warn!("unreadable draft of tab {}: {e}", tab.tab_key);
                None
            }
        });
    OpenTab {
        tab_key: tab.tab_key,
        position: tab.position,
        kind: tab.kind,
        order_id: tab.order_id,
        title: tab.title,
        active: tab.active,
        draft,
    }
}

impl Crm {
    /// Idle-lock minutes (0 = off).
    pub fn idle_lock_minutes(&self) -> Result<u32> {
        self.read(|c| Ok(settings::idle_lock_minutes(c)?))
    }

    /// Sets the idle-lock minutes, 0..=120.
    pub fn set_idle_lock_minutes(&self, minutes: u32) -> Result<()> {
        if !IDLE_LOCK_RANGE.contains(&minutes) {
            return Err(ServiceError::field(
                "idle_lock_minutes",
                messages::out_of_range(*IDLE_LOCK_RANGE.start(), *IDLE_LOCK_RANGE.end()),
            ));
        }
        self.write(move |tx| Ok(settings::set_idle_lock_minutes(tx, minutes)?))
    }

    /// Every open tab, by position.
    pub fn list_tabs(&self) -> Result<Vec<OpenTab>> {
        let stored = self.read(|c| Ok(tabs::list(c)?))?;
        Ok(stored.into_iter().map(from_stored).collect())
    }

    /// Inserts or overwrites the tab (by key), with its draft as JSON.
    pub fn save_tab(&self, tab: OpenTab) -> Result<()> {
        let draft_json = tab
            .draft
            .as_ref()
            .map(serde_json::to_string)
            .transpose()
            .map_err(|e| ServiceError::Storage(crm_storage::StorageError::Other(e.to_string())))?;
        let stored = tabs::OpenTab {
            tab_key: tab.tab_key,
            position: tab.position,
            kind: tab.kind,
            order_id: tab.order_id,
            title: tab.title,
            active: tab.active,
            draft_json,
            updated_at: time::now(),
        };
        self.write(move |tx| {
            tabs::upsert(tx, &stored)?;
            if stored.active {
                tabs::set_active(tx, &stored.tab_key)?;
            }
            Ok(())
        })
    }

    /// Closes one tab. Returns whether it existed.
    pub fn remove_tab(&self, tab_key: &str) -> Result<bool> {
        let key = tab_key.to_owned();
        self.write(move |tx| Ok(tabs::remove(tx, &key)?))
    }

    /// Closes every tab except `tab_key` ("Mbyll të tjerat").
    pub fn clear_tabs_except(&self, tab_key: &str) -> Result<()> {
        let key = tab_key.to_owned();
        self.write(move |tx| {
            for tab in tabs::list(tx)? {
                if tab.tab_key != key {
                    tabs::remove(tx, &tab.tab_key)?;
                }
            }
            Ok(())
        })
    }

    /// Closes every tab ("Mbyll të gjitha").
    pub fn clear_tabs(&self) -> Result<()> {
        self.write(|tx| Ok(tabs::clear_all(tx)?))
    }

    /// The receipt settings (defaults 72 mm, 9 pt). A stored value outside
    /// [`RECEIPT_WIDTH_RANGE`] / [`RECEIPT_FONT_RANGE`] (a database edited
    /// outside the app, or written by another build) reads as the default, so
    /// the renderer only ever sees in-range settings (F-021).
    pub fn receipt_settings(&self) -> Result<ReceiptSettings> {
        let stored = self.read(|c| {
            Ok(ReceiptSettings {
                width_mm: settings::receipt_width_mm(c)?,
                font_pt: settings::receipt_font_pt(c)?,
            })
        })?;
        Ok(ReceiptSettings {
            width_mm: in_range_or_default(
                "receipt_width_mm",
                stored.width_mm,
                RECEIPT_WIDTH_RANGE,
                settings::DEFAULT_RECEIPT_WIDTH_MM,
            ),
            font_pt: in_range_or_default(
                "receipt_font_pt",
                stored.font_pt,
                RECEIPT_FONT_RANGE,
                settings::DEFAULT_RECEIPT_FONT_PT,
            ),
        })
    }

    /// Stores the receipt settings (width 48..=110 mm, font 6..=14 pt).
    pub fn set_receipt_settings(&self, value: ReceiptSettings) -> Result<()> {
        let mut errors = Vec::new();
        for (field, v, range) in [
            ("width_mm", value.width_mm, RECEIPT_WIDTH_RANGE),
            ("font_pt", value.font_pt, RECEIPT_FONT_RANGE),
        ] {
            if !range.contains(&v) {
                errors.push(crm_domain::FieldError {
                    field,
                    line: None,
                    message: messages::out_of_range(*range.start(), *range.end()),
                });
            }
        }
        if !errors.is_empty() {
            return Err(ServiceError::Validation(crm_domain::ValidationErrors(
                errors,
            )));
        }
        self.write(move |tx| {
            settings::set_receipt_width_mm(tx, value.width_mm)?;
            Ok(settings::set_receipt_font_pt(tx, value.font_pt)?)
        })
    }
}
