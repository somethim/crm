-- Schema v1 (plan 001). The only migration of the first release; never edit it, add 002_*.sql instead.
CREATE TABLE settings (key TEXT PRIMARY KEY, value TEXT NOT NULL) STRICT;
-- keys: pin_hash, idle_lock_minutes (default '0' = off), receipt_width_mm ('72'),
--       receipt_font_pt ('9'), last_backup_at (RFC3339)
CREATE TABLE skus (
  id INTEGER PRIMARY KEY,
  code TEXT NOT NULL UNIQUE,                      -- base code, never "X/n"
  unit TEXT NOT NULL,
  buy_price INTEGER NOT NULL CHECK (buy_price >= 0),   -- qindarka
  sell_price INTEGER NOT NULL CHECK (sell_price >= 0),
  quantity INTEGER NOT NULL CHECK (quantity >= 0),
  created_at TEXT NOT NULL, updated_at TEXT NOT NULL) STRICT;
CREATE TABLE products (
  id INTEGER PRIMARY KEY,
  sku_id INTEGER NOT NULL REFERENCES skus(id) ON DELETE CASCADE,
  name TEXT NOT NULL, name_key TEXT NOT NULL,     -- name_key = domain::text::fold(name)
  created_at TEXT NOT NULL, updated_at TEXT NOT NULL,
  UNIQUE (sku_id, name)) STRICT;
CREATE INDEX products_name_key ON products(name_key);
CREATE TABLE owners (
  id INTEGER PRIMARY KEY,
  kind INTEGER NOT NULL CHECK (kind IN (0,1)),    -- 0 Klient, 1 Furnitor
  name TEXT NOT NULL, name_key TEXT NOT NULL,
  description TEXT, nipt TEXT, address TEXT,
  account_code TEXT,                              -- "Llogari"
  created_at TEXT NOT NULL, updated_at TEXT NOT NULL) STRICT;
CREATE INDEX owners_kind_name_key ON owners(kind, name_key);
CREATE INDEX owners_kind_nipt ON owners(kind, nipt);
CREATE UNIQUE INDEX owners_kind_account ON owners(kind, account_code) WHERE account_code IS NOT NULL;
CREATE TABLE orders (
  id INTEGER PRIMARY KEY AUTOINCREMENT,           -- "Nr. Fature"; never reused after delete
  kind INTEGER NOT NULL CHECK (kind IN (0,1)),    -- 0 Shitje, 1 Blerje
  owner_id INTEGER REFERENCES owners(id) ON DELETE SET NULL,
  owner_name TEXT NOT NULL, owner_description TEXT, owner_nipt TEXT, owner_address TEXT,
  search_key TEXT NOT NULL,                       -- fold(owner_name || ' ' || owner_description)
  issued_on TEXT NOT NULL,                        -- 'YYYY-MM-DD' (Q3/Q5)
  total INTEGER NOT NULL,
  created_at TEXT NOT NULL, updated_at TEXT NOT NULL) STRICT;
CREATE INDEX orders_kind_issued ON orders(kind, issued_on);
CREATE INDEX orders_issued ON orders(issued_on);
CREATE TABLE order_lines (
  id INTEGER PRIMARY KEY,
  order_id INTEGER NOT NULL REFERENCES orders(id) ON DELETE CASCADE,
  position INTEGER NOT NULL,
  product_id INTEGER REFERENCES products(id) ON DELETE SET NULL,
  sku_id INTEGER REFERENCES skus(id) ON DELETE SET NULL,   -- stock reversal survives product deletion
  name TEXT NOT NULL, code TEXT NOT NULL, unit TEXT NOT NULL,  -- snapshots
  quantity INTEGER NOT NULL CHECK (quantity > 0),
  price INTEGER NOT NULL CHECK (price >= 0),
  value INTEGER NOT NULL) STRICT;
CREATE INDEX order_lines_order ON order_lines(order_id);
CREATE INDEX order_lines_product ON order_lines(product_id);
CREATE TABLE open_tabs (
  tab_key TEXT PRIMARY KEY,                       -- uuid-like string generated by ui
  position INTEGER NOT NULL,
  kind INTEGER NOT NULL CHECK (kind IN (0,1)),
  order_id INTEGER REFERENCES orders(id) ON DELETE CASCADE,
  title TEXT NOT NULL,
  active INTEGER NOT NULL DEFAULT 0,
  draft_json TEXT,                                -- NULL = no unsaved changes
  updated_at TEXT NOT NULL) STRICT;
